<script setup>
import { computed, ref } from 'vue'
import { FileCode2, Upload, AlertTriangle, X } from 'lucide-vue-next'
import { parsePostgresDDL } from '../sqlImport.js'
import { useModelStore } from '../stores/modelador.js'

const emit=defineEmits(['imported'])
const store=useModelStore()
const modal=ref(null)
const fileInput=ref(null)
const sql=ref('')
const mode=ref('merge')
const preview=ref(null)
const error=ref('')
const acceptReplace=ref(false)
const applying=ref(false)
const checkedText=ref('')
const canApply=computed(()=>preview.value&&sql.value===checkedText.value&&(mode.value!=='replace'||acceptReplace.value))

function open(){
  sql.value=''
  preview.value=null
  checkedText.value=''
  error.value=''
  mode.value='merge'
  acceptReplace.value=false
  modal.value?.showModal()
}
function invalidate(){preview.value=null;checkedText.value='';error.value='';acceptReplace.value=false}
async function upload(event){
  const file=event.target.files?.[0]
  if(!file)return
  try{
    if(file.size>4*1024*1024)throw new Error('O arquivo SQL deve ter até 4 MB.')
    sql.value=await file.text()
    invalidate()
  }catch(e){error.value=e.message}
  finally{event.target.value=''}
}
function analyze(){
  invalidate()
  try{
    const result=parsePostgresDDL(sql.value,store.doc.schema)
    if(mode.value==='merge'&&store.doc.tabelas.length&&store.doc.schema.trim().toLowerCase()!==result.schema_alvo.trim().toLowerCase()){
      throw new Error('O schema importado ('+result.schema_alvo+') é diferente do projeto ('+store.doc.schema+').')
    }
    preview.value=result
    checkedText.value=sql.value
  }catch(e){error.value=e.message}
}
function apply(){
  if(!canApply.value||applying.value)return
  applying.value=true
  error.value=''
  try{
    const outcome=store.importSql(checkedText.value,mode.value)
    emit('imported',outcome,mode.value)
    modal.value.close()
  }catch(e){error.value='Falha na importação: '+e.message}
  finally{applying.value=false}
}
defineExpose({open})
</script>

<template>
  <dialog ref="modal" class="sql-import-dialog" aria-labelledby="sql-import-title">
    <div class="sql-import-header">
      <div><h2 id="sql-import-title"><FileCode2 :size="21"/> Importar definição SQL</h2>
      <p>Crie tabelas no modelador usando DDL PostgreSQL ou um dump de schema do Supabase. Nenhum SQL é executado no banco.</p></div>
      <button class="iconbtn" title="Fechar" aria-label="Fechar" @click="modal.close()"><X :size="18"/></button>
    </div>
    <div class="sql-import-content">
      <label class="sql-import-label" for="sql-definition">Cole comandos CREATE TABLE, CREATE TYPE, CREATE FUNCTION, CREATE TRIGGER e ALTER TABLE</label>
      <textarea id="sql-definition" v-model="sql" class="sql-import-editor" rows="10" spellcheck="false"
        placeholder="CREATE TABLE rpg.fichas (&#10;  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,&#10;  nome VARCHAR(100) NOT NULL&#10;);" @input="invalidate"/>
      <div class="sql-import-options">
        <button class="btn" type="button" @click="fileInput.click()"><Upload :size="15"/> Selecionar .sql ou .txt</button>
        <input ref="fileInput" type="file" accept=".sql,.txt,text/plain,application/sql" hidden @change="upload"/>
        <span>{{sql.length.toLocaleString('pt-BR')}} caracteres</span>
      </div>
      <fieldset class="sql-import-modes">
        <legend>Como importar?</legend>
        <label :class="{selected:mode==='merge'}">
          <input v-model="mode" name="importMode" type="radio" value="merge"/>
          <span><strong>Mesclar com o projeto</strong><small>Adiciona tabelas e colunas que ainda não existem. Mantém as existentes e incorpora novas restrições, funções e triggers.</small></span>
        </label>
        <label :class="{selected:mode==='replace'}">
          <input v-model="mode" name="importMode" type="radio" value="replace"/>
          <span><strong>Substituir modelo atual</strong><small>Remove do editor as tabelas antigas e carrega somente as do SQL. Não altera o banco PostgreSQL real.</small></span>
        </label>
      </fieldset>
      <div v-if="preview" class="sql-import-summary" aria-live="polite">
        <strong>Prévia do SQL analisado ({{preview.schema_alvo}})</strong>
        <p>{{preview.resumo.tabelas}} tabelas · {{preview.resumo.colunas}} colunas · {{preview.resumo.restricoes}} restrições · {{preview.resumo.triggers}} triggers · {{preview.resumo.enums}} enums · {{preview.resumo.funcoes}} funções · {{preview.resumo.politicas}} políticas/RLS · {{preview.resumo.comentarios}} comentários globais</p>
        <details v-if="preview.avisos.length"><summary><AlertTriangle :size="14"/> {{preview.avisos.length}} avisos sobre tipos ou comandos adicionais</summary>
          <ul><li v-for="(warning,i) in preview.avisos.slice(0,12)" :key="i">{{warning}}</li></ul>
          <p v-if="preview.avisos.length>12">Outros {{preview.avisos.length-12}} avisos omitidos nesta prévia.</p>
        </details>
      </div>
      <label v-if="preview&&mode==='replace'" class="sql-replace-ack">
        <input v-model="acceptReplace" type="checkbox"/>
        Confirmo que quero substituir todas as tabelas deste projeto no modelador.
      </label>
      <p v-if="error" class="sql-import-error" role="alert">{{error}}</p>
    </div>
    <div class="sql-import-footer">
      <button class="btn" type="button" @click="modal.close()">Cancelar</button>
      <button class="btn" type="button" :disabled="!sql.trim()||applying" @click="analyze">Analisar SQL</button>
      <button class="btn" :class="mode==='replace'?'danger':'primary'" type="button" :disabled="!canApply||applying" @click="apply">
        {{mode==='replace'?'Substituir projeto':'Mesclar importação'}}
      </button>
    </div>
  </dialog>
</template>
