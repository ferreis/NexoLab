import test from 'node:test'
import assert from 'node:assert/strict'
import { parsePostgresDDL, splitSqlStatements } from '../src/sqlImport.js'

test('função com ponto e vírgula e comentários não divide o CREATE TABLE',()=>{
  const sql=String.raw`-- antes
CREATE OR REPLACE FUNCTION rpg.bloquear() RETURNS trigger
LANGUAGE plpgsql AS $fn$
BEGIN RAISE EXCEPTION 'sem permissão; mesmo no UPDATE'; END
$fn$;
CREATE TABLE rpg.fichas (id bigint PRIMARY KEY, nome text NOT NULL);
-- depois`
  assert.equal(splitSqlStatements(sql).length,2)
  const data=parsePostgresDDL(sql)
  assert.equal(data.resumo.funcoes,1)
  assert.equal(data.tabelas.length,1)
  assert.equal(data.tabelas[0].colunas[0].pk,true)
})
test('CREATE TABLE do Supabase mantém tipos, check composto, fks, identidade e trigger',()=>{
  const sql=String.raw`
CREATE TYPE rpg.segredos_tipo AS ENUM ('proprio','corrige');
create table rpg.fichas (id bigint primary key);
create table rpg.segredos (
 id bigint generated by default as identity not null,
 ficha_id bigint null,
 descricao character varying(1000) not null,
 tipo rpg.segredos_tipo not null default 'proprio'::rpg.segredos_tipo,
 criado_em timestamp with time zone not null default now(),
 constraint segredos_pkey primary key (id),
 constraint segredos_fk foreign key (ficha_id) references rpg.fichas (id),
 constraint segredos_check check ((num_nonnulls(ficha_id, id) = 1)),
 constraint segredos_check2 check ((tipo = 'proprio'::rpg.segredos_tipo))
) TABLESPACE pg_default;
create trigger bloquear_segredos BEFORE DELETE or UPDATE on rpg.segredos
for each row execute function rpg.bloquear();
`
  const data=parsePostgresDDL(sql)
  const tabela=data.tabelas.find(t=>t.nome==='segredos')
  assert.equal(tabela.colunas.find(c=>c.nome==='id').padrao,'GENERATED BY DEFAULT AS IDENTITY')
  assert.equal(tabela.colunas.find(c=>c.nome==='descricao').tamanho,'1000')
  assert.equal(tabela.colunas.find(c=>c.nome==='tipo').tipo,'ENUM')
  assert.deepEqual(tabela.colunas.find(c=>c.nome==='tipo').enumValores,['proprio','corrige'])
  assert.equal(tabela.colunas.find(c=>c.nome==='ficha_id').fkTabela,'fichas')
  assert.equal(tabela.colunas.find(c=>c.nome==='criado_em').tipo,'TIMESTAMPTZ')
  assert.equal(tabela.sqlRestricoes.length,4)
  assert.equal(tabela.sqlTriggers.length,1)
})
test('pg_dump reconhece ALTER TABLE PK e identidade, comentários e UNIQUE composto',()=>{
  const sql=String.raw`
CREATE TABLE IF NOT EXISTS "rpg"."financeiros" (
 "id" bigint NOT NULL,
 "saldo" numeric(17, 2) DEFAULT 0 NOT NULL,
 "a" bigint, "b" bigint
);
ALTER TABLE "rpg"."financeiros" ALTER COLUMN "id" ADD GENERATED BY DEFAULT AS IDENTITY (
 SEQUENCE NAME "rpg"."financeiros_id_seq" START WITH 1
);
ALTER TABLE ONLY "rpg"."financeiros" ADD CONSTRAINT "financeiros_pkey" PRIMARY KEY ("id");
ALTER TABLE ONLY "rpg"."financeiros" ADD CONSTRAINT "financeiros_unique" UNIQUE ("a","b");
COMMENT ON TABLE "rpg"."financeiros" IS 'Controle financeiro';
COMMENT ON COLUMN "rpg"."financeiros"."saldo" IS 'Saldo atualizado';
`
  const d=parsePostgresDDL(sql)
  const t=d.tabelas[0]
  assert.equal(t.colunas.find(c=>c.nome==='id').pk,true)
  assert.equal(t.colunas.find(c=>c.nome==='id').padrao,'GENERATED BY DEFAULT AS IDENTITY')
  assert.equal(t.colunas.find(c=>c.nome==='saldo').escala,'2')
  assert.equal(t.colunas.find(c=>c.nome==='saldo').comentario,'Saldo atualizado')
  assert.equal(t.comentario,'Controle financeiro')
  assert.deepEqual(t.uniqueCompostos[0].colunas,['a','b'])
})
test('preserva tipo PostgreSQL não conhecido em vez de inventar outra semântica',()=>{
  const d=parsePostgresDDL('CREATE TABLE rpg.arquivos (id bigint PRIMARY KEY, dados bytea NOT NULL);')
  assert.equal(d.tabelas[0].colunas[1].tipo,'CUSTOM')
  assert.equal(d.tabelas[0].colunas[1].sqlTipoOriginal,'bytea')
  assert.ok(d.avisos.some(v=>v.includes('bytea')))
})
test('recusa texto sem tabela e importação com mais de um schema',()=>{
  assert.throws(()=>parsePostgresDDL('DROP TABLE rpg.fichas'),/CREATE TABLE/)
  assert.throws(()=>parsePostgresDDL('CREATE TABLE rpg.a (id bigint);CREATE TABLE public.b (id bigint);'),/único schema/)
})
