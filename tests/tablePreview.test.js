import test from 'node:test'
import assert from 'node:assert/strict'
import { tablePreview } from '../src/tablePreview.js'
import { formatText } from '../src/textExport.js'

const model={
  formato:'proposta_de_modelagem_banco_rpg',
  projeto:'RPG',
  schema_alvo:'rpg',
  enums:[{nome:'segredos_tipo',sql:"CREATE TYPE rpg.segredos_tipo AS ENUM ('proprio');"}],
  funcoesSql:["CREATE FUNCTION rpg.fn_contexto_cena() RETURNS void AS $$ BEGIN END $$ LANGUAGE plpgsql;"],
  comentariosSql:["COMMENT ON SCHEMA rpg IS 'Contexto geral';"],
  tabelas:[
    {nome:'arcos',comentario:'',uniqueCompostos:[],sqlRestricoes:['CONSTRAINT arcos_pkey PRIMARY KEY (id)'],
      sqlTriggers:['CREATE TRIGGER atualizar_arcos BEFORE UPDATE ON rpg.arcos FOR EACH ROW EXECUTE FUNCTION rpg.validar_atualizacao();'],
      sqlIndices:[],sqlPoliticas:[],
      colunas:[{nome:'id',tipo:'BIGINT',tamanho:'',escala:'',nullable:false,pk:true,unique:true,padrao:'GENERATED BY DEFAULT AS IDENTITY',imutavel:true,fk:false,checks:[],descricao:'Identificador único automático.',comentario:''}]},
    {nome:'fichas',comentario:'',uniqueCompostos:[],colunas:[{nome:'id',tipo:'BIGINT',tamanho:'',escala:'',nullable:false,pk:true,unique:true,padrao:'',imutavel:true,fk:false,checks:[],descricao:'',comentario:''}]}
  ]
}

test('prévia da tabela mostra somente a tabela selecionada e suas regras',()=>{
  const preview=tablePreview(model,0)
  const text=formatText(preview)
  assert.deepEqual(preview.tabelas.map(t=>t.nome),['arcos'])
  assert.match(text,/TABELA: arcos/)
  assert.match(text,/Restrições SQL:/)
  assert.match(text,/Triggers SQL:/)
  assert.doesNotMatch(text,/TABELA: fichas/)
  assert.doesNotMatch(text,/ENUMs do schema:|Funções SQL:|Comentários SQL globais:/)
  assert.doesNotMatch(text,/segredos_tipo|fn_contexto_cena|Contexto geral/)
  const json=JSON.stringify(preview)
  assert.doesNotMatch(json,/segredos_tipo|fn_contexto_cena|Contexto geral/)
  assert.ok(!Object.hasOwn(preview,'enums'))
  assert.ok(!Object.hasOwn(preview,'funcoesSql'))
  assert.ok(!Object.hasOwn(preview,'comentariosSql'))
})

test('visualização completa mantém definições globais do schema',()=>{
  const text=formatText(model)
  assert.match(text,/ENUMs do schema:/)
  assert.match(text,/Funções SQL:/)
  assert.match(text,/Comentários SQL globais:/)
  assert.match(text,/TABELA: arcos/)
  assert.match(text,/TABELA: fichas/)
})

test('não altera o modelo original e apresenta lista vazia para índice inválido',()=>{
  const before=JSON.stringify(model)
  assert.deepEqual(tablePreview(model,-1).tabelas,[])
  assert.deepEqual(tablePreview(model,99).tabelas,[])
  assert.equal(JSON.stringify(model),before)
})
