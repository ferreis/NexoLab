import test from 'node:test'
import assert from 'node:assert/strict'
import { copyColumnsInDocument } from '../src/columnCopy.js'
import { createPinia, setActivePinia } from 'pinia'
import { useModelStore } from '../src/stores/modelador.js'

const field=(uid,nome,extras={})=>({uid,nome,tipo:'SMALLINT',nullable:false,checks:[],...extras})
function project(){
  return {schema:'rpg',funcoesSql:['CREATE FUNCTION rpg.validar() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;'],
    tabelas:[
      {uid:'src',nome:'fichas',colunas:[
        field('a','forca',{checks:[{uid:'check',expressao:'forca >= 0',origemRestricao:'CONSTRAINT c CHECK (forca >= 0)'}],checkEnabled:true,pk:true,unique:true,padrao:'GENERATED BY DEFAULT AS IDENTITY',descricao:'Força.'}),
        field('b','destreza',{fk:true,fkTabela:'public.pessoas',fkColuna:'id',tipo:'UUID'}),
        field('c','nivel',{tipo:'INTEGER',nullable:true,descricao:'Progressão.'})
      ],uniqueCompostos:[],sqlTriggers:['CREATE TRIGGER trig BEFORE UPDATE ON rpg.fichas FOR EACH ROW EXECUTE FUNCTION rpg.validar();'],sqlRestricoes:['CONSTRAINT c CHECK (forca >= 0)']},
      {uid:'dest',nome:'atributos',colunas:[field('d','forca'),field('e','codigo')],uniqueCompostos:[],sqlTriggers:[],sqlRestricoes:[]}
    ]}
}
test('copia só atributos estruturais, sem CHECK/PK/UNIQUE/FK, sem alterar origem',()=>{
  const doc=project(),old=structuredClone(doc.tabelas[0])
  const result=copyColumnsInDocument(doc,'src','dest',['a','b'])
  assert.equal(result.copied,2)
  assert.deepEqual(result.columns,['forca_copia','destreza'])
  assert.deepEqual(doc.tabelas[0],old)
  assert.deepEqual(doc.funcoesSql,project().funcoesSql)
  const [a,b]=doc.tabelas[1].colunas.slice(2)
  assert.equal(a.nome,'forca_copia')
  assert.equal(a.descricao,'Força.')
  assert.notEqual(a.uid,'a')
  assert.equal(a.pk,false)
  assert.equal(a.unique,false)
  assert.equal(a.uniqueComposto,false)
  assert.equal(a.checkEnabled,false)
  assert.deepEqual(a.checks,[])
  assert.equal(a.padrao,'')
  assert.equal(a.imutavel,false)
  assert.equal(b.tipo,'UUID')
  assert.equal(b.fk,false)
  assert.equal(b.fkTabela,'')
  assert.equal(b.fkColuna,'id')
  assert.deepEqual(doc.tabelas[1].sqlTriggers,[])
  assert.deepEqual(doc.tabelas[1].sqlRestricoes,[])
})
test('preserva o nome quando estiver disponível e cria sufixo incremental em conflito',()=>{
  const doc=project()
  copyColumnsInDocument(doc,'src','dest',['a'])
  copyColumnsInDocument(doc,'src','dest',['a'])
  assert.deepEqual(doc.tabelas[1].colunas.map(c=>c.nome),['forca','codigo','forca_copia','forca_copia_2'])
})
test('aceita copiar várias colunas sem perder ordem, tipos e nulidade',()=>{
  const doc=project()
  copyColumnsInDocument(doc,'src','dest',['c','b'])
  assert.deepEqual(doc.tabelas[1].colunas.map(c=>c.nome),['forca','codigo','destreza','nivel'])
  assert.equal(doc.tabelas[1].colunas.at(-1).nullable,true)
})
test('validação impede cópias inválidas sem mutações parciais',()=>{
  const doc=project()
  for(const [source,target,ids] of [
    ['src','src',['a']],['src','missing',['a']],['missing','dest',['a']],
    ['src','dest',[]],['src','dest',['a','a']],['src','dest',['not-here']]
  ]){
    const before=JSON.stringify(doc)
    assert.throws(()=>copyColumnsInDocument(doc,source,target,ids))
    assert.equal(JSON.stringify(doc),before)
  }
})
test('store copia e persiste mantendo CHECKs, triggers e funções da origem',()=>{
  globalThis.localStorage={getItem:()=>null,setItem:()=>{}}
  setActivePinia(createPinia())
  const store=useModelStore()
  const doc=project()
  store.importData({...doc,tabelas:doc.tabelas.map(t=>({...t}))})
  const src=store.doc.tabelas.find(t=>t.nome==='fichas')
  const dest=store.doc.tabelas.find(t=>t.nome==='atributos')
  const result=store.copyColumns(src.uid,dest.uid,[src.colunas.find(c=>c.nome==='forca').uid])
  assert.equal(result.copied,1)
  assert.equal(store.doc.tabelas.find(t=>t.nome==='fichas').colunas[0].checks.length,1)
  assert.equal(store.doc.tabelas.find(t=>t.nome==='fichas').sqlTriggers.length,1)
  assert.equal(store.doc.funcoesSql.length,1)
  assert.equal(store.doc.tabelas.find(t=>t.nome==='atributos').colunas.at(-1).checks.length,0)
})
