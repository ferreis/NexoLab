import test from 'node:test'
import assert from 'node:assert/strict'
import { createPinia, setActivePinia } from 'pinia'
import { useModelStore } from '../src/stores/modelador.js'
import { parsePostgresDDL } from '../src/sqlImport.js'

const sql=String.raw`
CREATE TABLE rpg.cenas_acoes (
  id bigint generated by default as identity not null,
  cena_id bigint,
  cena_acao_id bigint,
  descricao text not null,
  CONSTRAINT cenas_acoes_pkey PRIMARY KEY(id),
  CONSTRAINT cenas_acoes_check CHECK ((num_nonnulls(cena_id, cena_acao_id) = 1))
);
CREATE TABLE rpg.cenas_log (
  id bigint primary key,
  cena_acao_id bigint REFERENCES rpg.cenas_acoes(id)
);
ALTER TABLE ONLY rpg.cenas_log ADD CONSTRAINT cena_log_check CHECK (cena_acao_id > 0);
`
const init=()=>{
  globalThis.localStorage={getItem:()=>null,setItem:()=>{}}
  setActivePinia(createPinia())
  return useModelStore()
}

test('CHECKs da tabela e ALTER TABLE são importados como CHECKs editáveis',()=>{
  const parsed=parsePostgresDDL(sql)
  const checks=parsed.tabelas.flatMap(t=>t.colunas.flatMap(c=>c.checks))
  assert.equal(checks.length,2)
  const store=init()
  store.importSql(sql,'replace')
  const c=store.doc.tabelas.find(t=>t.nome==='cenas_acoes').colunas.find(c=>c.nome==='cena_id')
  assert.equal(c.checks.length,1)
  assert.match(c.checks[0].expressao,/num_nonnulls/)
  assert.equal(c.checkEnabled,true)
  assert.ok(c.checks[0].origemRestricao)
  store.importSql(sql,'merge')
  assert.equal(c.checks.length,1)
})

test('editar e remover CHECK importado atualiza também a definição SQL',()=>{
  const store=init()
  store.importSql(sql,'replace')
  const table=store.selected
  const column=table.colunas.find(c=>c.nome==='cena_id')
  const id=column.checks[0].uid
  store.saveCheck(column,id,'cena_id IS NOT NULL')
  assert.match(table.sqlRestricoes.join('\n'),/CHECK \(cena_id IS NOT NULL\)/)
  assert.doesNotMatch(table.sqlRestricoes.join('\n'),/num_nonnulls/)
  store.removeCheck(column,id)
  assert.equal(column.checks.length,0)
  assert.doesNotMatch(table.sqlRestricoes.join('\n'),/cenas_acoes_check/)
})
test('renomear tabela refatora FK e nome de coluna, preservando CHECK',()=>{
  const store=init()
  store.importSql(sql,'replace')
  const target=store.doc.tabelas.find(t=>t.nome==='cenas_acoes')
  const before=target.uid
  const result=store.renameTable(target,'acoes')
  const ref=store.doc.tabelas.find(t=>t.nome==='cenas_log').colunas.find(c=>c.fk)
  assert.equal(target.uid,before)
  assert.equal(ref.fkTabela,'acoes')
  assert.equal(ref.nome,'acao_id')
  assert.match(store.doc.tabelas.find(t=>t.nome==='cenas_log').sqlRestricoes.join('\n'),/acao_id/)
  assert.equal(result.foreignKeys,1)
})
test('edição em massa substitui trechos e evita colisões sem salvar parcialmente',()=>{
  const store=init()
  store.importSql(sql,'replace')
  const table=store.selected
  const first=table.colunas.find(c=>c.nome==='cena_id')
  const second=table.colunas.find(c=>c.nome==='cena_acao_id')
  assert.throws(()=>store.bulkRenameColumns([first.uid,second.uid],'cena',''),/Já existe uma coluna|nome/)
  const before=JSON.stringify(store.exported)
  assert.throws(()=>store.bulkRenameColumns([first.uid,second.uid],'cena_',''),/Já existe uma coluna|nome/)
  assert.equal(JSON.stringify(store.exported),before)
  const result=store.bulkRenameColumns([first.uid,second.uid],'cena','acao')
  assert.equal(result.changed,2)
  assert.ok(store.selected.colunas.some(c=>c.nome==='acao_id'))
  assert.match(store.selected.colunas.find(c=>c.nome==='acao_id').checks[0].expressao,/acao_id/)
})
test('colunas padrão podem ser criadas e atualizadas em todas as tabelas, sem duplicação',()=>{
  const store=init()
  store.importSql(sql,'replace')
  const first=store.addDefaults('all')
  assert.equal(first.tables,2)
  for(const t of store.doc.tabelas){
    const cols=t.colunas.filter(c=>['id','criado_em','atualizado_em'].includes(c.nome))
    assert.equal(cols.length,3)
    assert.equal(cols.find(c=>c.nome==='id').padrao,'GENERATED BY DEFAULT AS IDENTITY')
    assert.equal(cols.find(c=>c.nome==='id').unique,true)
    assert.equal(cols.find(c=>c.nome==='criado_em').imutavel,true)
    assert.equal(cols.find(c=>c.nome==='atualizado_em').padrao,'now()')
    assert.equal(cols.find(c=>c.nome==='atualizado_em').imutavel,false)
  }
  const second=store.addDefaults('all')
  assert.equal(second.created,0)
})
test('preserva PK diferente de id ao aplicar padrões globais',()=>{
  const store=init()
  store.importData({schema:'rpg',tabelas:[{nome:'config',colunas:[{nome:'chave',tipo:'TEXT',pk:true}]}]})
  const report=store.addDefaults('all')
  assert.equal(report.skipped,1)
  assert.equal(store.selected.colunas.filter(c=>c.pk).length,1)
  assert.equal(store.selected.colunas.find(c=>c.pk).nome,'chave')
  assert.ok(store.selected.colunas.find(c=>c.nome==='criado_em'))
})
